@app.get("/api/events")
def get_events():

    events = read_events()

    formatted_events = []

    for event in events:

        event_copy = dict(event)

        # Make sure severity always comes from backend
        event_copy["severity"] = calculate_severity(event)

        formatted_events.append(event_copy)

    # Newest events first
    formatted_events.reverse()

    return formatted_events


# =========================================================
# COMMANDS
# =========================================================

@app.get("/api/commands")
def get_commands():

    events = read_events()

    commands = []

    for event in events:

        event_id = event.get("eventid", "")

        if event_id == "cowrie.command.input":

            commands.append(
                {
                    "timestamp": event.get("timestamp"),
                    "ip": event.get("src_ip"),
                    "session": event.get("session"),
                    "command": event.get("input", ""),
                    "severity": calculate_severity(event),
                }
            )

    return list(reversed(commands))


# =========================================================
# LOGIN ATTEMPTS
# =========================================================

@app.get("/api/logins")
def get_logins():

    events = read_events()

    logins = []

    for event in events:

        event_id = event.get("eventid", "")

        if event_id in [
            "cowrie.login.failed",
            "cowrie.login.success",
        ]:

            logins.append(
                {
                    "timestamp": event.get("timestamp"),
                    "ip": event.get("src_ip"),
                    "username": event.get("username"),
                    "password": event.get("password"),
                    "success": event_id
                    == "cowrie.login.success",
                    "severity": calculate_severity(event),
                }
            )

    return list(reversed(logins))


