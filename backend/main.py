# =========================================================
# RISK CALCULATION
# =========================================================

def calculate_attacker_risk(events):
    """
    Calculate the risk score for one attacker
    based on the events generated by Cowrie.
    """

    score = 0

    for event in events:

        event_id = event.get("eventid", "")

        # Failed login attempt
        if event_id == "cowrie.login.failed":
            score += 10

        # Successful login
        elif event_id == "cowrie.login.success":
            score += 30

        # Command executed
        elif event_id == "cowrie.command.input":

            # Base command score
            score += 15

            # Extra weight for dangerous commands
            command = (event.get("input") or "").lower()

            critical_commands = [
                "rm -rf",
                "mkfs",
                "dd if=",
                "shutdown",
                "reboot",
            ]

            high_commands = [
                "wget",
                "curl",
                "chmod +x",
                "nc ",
                "netcat",
                "bash -i",
                "python -c",
                "perl -e",
            ]

            if any(item in command for item in critical_commands):
                score += 30

            elif any(item in command for item in high_commands):
                score += 20

        # Failed command
        elif event_id == "cowrie.command.failed":
            score += 5

        # New SSH session
        elif event_id == "cowrie.session.connect":
            score += 2

    # -----------------------------------------------------
    # Risk level
    # -----------------------------------------------------

    if score >= 70:
        risk_level = "CRITICAL"

    elif score >= 40:
        risk_level = "HIGH"

    elif score >= 20:
        risk_level = "MEDIUM"

    else:
        risk_level = "LOW"

    return score, risk_level


