@app.get("/api/attackers/{ip}/risk")
def get_attacker_risk(ip: str):

    events = read_events()

    attacker_events = [
        event
        for event in events
        if event.get("src_ip") == ip
    ]

    score, risk_level = calculate_attacker_risk(
        attacker_events
    )

    return {
        "ip": ip,
        "risk_score": score,
        "risk_level": risk_level,
        "events": len(attacker_events),
    }


